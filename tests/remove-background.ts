import assert from "node:assert/strict";
import { CUTOUT_SIZE, MAX_CUTOUT_PIXELS, cutoutMaskPixels, normalizeCutoutPixels } from "../src/lib/remove-bg-pixels";
const count = CUTOUT_SIZE * CUTOUT_SIZE;
const source = new Uint8ClampedArray(count * 4);
for (let i = 3; i < source.length; i += 4) source[i] = 255;
source[0] = 255; source[1] = 128; source[2] = 64;
const tensor = normalizeCutoutPixels(source);
assert.equal(tensor.length, count * 3);
assert.ok(Math.abs(tensor[0] - (1 - .485) / .229) < 1e-5);
assert.ok(Math.abs(tensor[count] - (128 / 255 - .456) / .224) < 1e-5);
assert.equal(source[0], 255, "normalization must not change the source");
assert.throws(() => normalizeCutoutPixels(new Uint8ClampedArray(4)));
const black = normalizeCutoutPixels(new Uint8ClampedArray(count * 4));
assert.ok(black.every(Number.isFinite), "black inputs must not divide by zero");
const mask = new Float32Array(count); mask[0] = .25; mask[1] = .75;
const alpha = cutoutMaskPixels(mask);
assert.equal(alpha[3], 85); assert.equal(alpha[7], 255); assert.equal(alpha[11], 0);
assert.equal(alpha[0], 255);
assert.throws(() => cutoutMaskPixels(new Float32Array(count)), /No usable subject/);
mask[0] = NaN; assert.throws(() => cutoutMaskPixels(mask), /invalid mask/);
assert.equal(MAX_CUTOUT_PIXELS, 8_000_000);
console.log("Background-removal preprocessing and mask regression checks passed.");
